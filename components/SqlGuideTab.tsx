'use client';

import React, { useState } from 'react';
import { Database, Copy, Check, ExternalLink, ShieldAlert, CheckCircle2, Play, RefreshCw, Info } from 'lucide-react';
import { supabase } from '@/lib/supabase';

interface SqlGuideTabProps {
  onRefreshData: () => Promise<void>;
  showToast: (type: 'success' | 'error' | 'warning' | 'info', message: string, title?: string) => void;
}

const SQL_SCRIPT = `-- ==============================================================
-- SCRIPT DE CONFIGURACIÓN SUPABASE - SUTIAGA & MUTUAL
-- Ejecuta este script en el SQL Editor de Supabase
-- ==============================================================

-- 1. TABLA LOCALIDADES
CREATE TABLE IF NOT EXISTS localidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    localidad TEXT NOT NULL,
    provincia TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. TABLA BENEFICIOS
CREATE TABLE IF NOT EXISTS beneficios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_empresa TEXT NOT NULL,
    logo TEXT,
    beneficio TEXT NOT NULL,
    localidad TEXT NOT NULL,
    direccion TEXT NOT NULL,
    organizacion TEXT NOT NULL DEFAULT 'AMBAS',
    seccion TEXT DEFAULT 'General',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. TABLA AFILIADOS
CREATE TABLE IF NOT EXISTS afiliados (
    dni TEXT PRIMARY KEY,
    nombre_completo TEXT NOT NULL,
    correo TEXT NOT NULL,
    contrasena TEXT NOT NULL,
    organizacion TEXT NOT NULL DEFAULT 'SUTIAGA',
    familiares JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 4. ASEGURAR COLUMNAS SI LAS TABLAS YA EXISTÍAN
ALTER TABLE afiliados ADD COLUMN IF NOT EXISTS organizacion TEXT DEFAULT 'SUTIAGA';
ALTER TABLE afiliados ADD COLUMN IF NOT EXISTS familiares JSONB DEFAULT '[]'::jsonb;
ALTER TABLE afiliados ADD COLUMN IF NOT EXISTS contrasena TEXT;
ALTER TABLE afiliados ADD COLUMN IF NOT EXISTS correo TEXT;
ALTER TABLE afiliados ADD COLUMN IF NOT EXISTS nombre_completo TEXT;

ALTER TABLE beneficios ADD COLUMN IF NOT EXISTS organizacion TEXT DEFAULT 'AMBAS';
ALTER TABLE beneficios ADD COLUMN IF NOT EXISTS seccion TEXT DEFAULT 'General';
ALTER TABLE beneficios ADD COLUMN IF NOT EXISTS logo TEXT;
ALTER TABLE beneficios ADD COLUMN IF NOT EXISTS beneficio TEXT;
ALTER TABLE beneficios ADD COLUMN IF NOT EXISTS localidad TEXT;
ALTER TABLE beneficios ADD COLUMN IF NOT EXISTS direccion TEXT;

-- 4.1 ACTUALIZAR SECCIONES DE CONVENIOS EXISTENTES
UPDATE beneficios SET seccion = 'Automotor' WHERE nombre_empresa ILIKE '%Chapa y Pintura%' OR nombre_empresa ILIKE '%Gorillas%' OR nombre_empresa ILIKE '%Lubricentro%' OR nombre_empresa ILIKE '%Detail Garage%';
UPDATE beneficios SET seccion = 'Hogar y Bazar' WHERE nombre_empresa ILIKE '%Shopping del sur%' OR nombre_empresa ILIKE '%El Obrero%' OR nombre_empresa ILIKE '%MEGASHOP%' OR nombre_empresa ILIKE '%Naldo%';
UPDATE beneficios SET seccion = 'Salud' WHERE nombre_empresa ILIKE '%Optica Martinez%' OR nombre_empresa ILIKE '%Farmacia Social%' OR nombre_empresa ILIKE '%Mediven%';
UPDATE beneficios SET seccion = 'Belleza y Bienestar' WHERE nombre_empresa ILIKE '%Azabache%' OR nombre_empresa ILIKE '%MC Barber%' OR nombre_empresa ILIKE '%Nicecut%' OR nombre_empresa ILIKE '%Viru Tattoo%' OR nombre_empresa ILIKE '%Gema hotel%';
UPDATE beneficios SET seccion = 'Comercio' WHERE nombre_empresa ILIKE '%Flores%' OR nombre_empresa ILIKE '%Market Mutual%' OR nombre_empresa ILIKE '%Jalejo%';
UPDATE beneficios SET seccion = 'Deporte' WHERE nombre_empresa ILIKE '%Acuarium%';
UPDATE beneficios SET seccion = 'Eventos Celebraciones' WHERE nombre_empresa ILIKE '%Antonella Turchet%';

-- 5. PERMISOS Y SEGURIDAD A NIVEL DE FILAS (RLS)
-- Deshabilita RLS para permitir Altas, Bajas y Modificaciones directas desde la aplicación:
ALTER TABLE afiliados DISABLE ROW LEVEL SECURITY;
ALTER TABLE beneficios DISABLE ROW LEVEL SECURITY;
ALTER TABLE localidades DISABLE ROW LEVEL SECURITY;

-- 6. DATOS DE EJEMPLO INICIALES (OPCIONAL)
INSERT INTO localidades (localidad, provincia)
SELECT 'Rosario', 'Santa Fe'
WHERE NOT EXISTS (SELECT 1 FROM localidades LIMIT 1);

INSERT INTO localidades (localidad, provincia)
SELECT 'Santa Fe Capital', 'Santa Fe'
WHERE NOT EXISTS (SELECT 1 FROM localidades WHERE localidad = 'Santa Fe Capital');

INSERT INTO localidades (localidad, provincia)
SELECT 'Venado Tuerto', 'Santa Fe'
WHERE NOT EXISTS (SELECT 1 FROM localidades WHERE localidad = 'Venado Tuerto');

INSERT INTO beneficios (nombre_empresa, logo, beneficio, localidad, direccion)
SELECT 
    'Farmacia Central', 
    'https://images.unsplash.com/photo-1587854692152-cbe660dbde88?w=200&auto=format&fit=crop&q=80',
    '25% de descuento en medicamentos recetados y 15% en perfumería', 
    'Rosario', 
    'San Martín 1250'
WHERE NOT EXISTS (SELECT 1 FROM beneficios LIMIT 1);
`;

export const SqlGuideTab: React.FC<SqlGuideTabProps> = ({ onRefreshData, showToast }) => {
  const [copied, setCopied] = useState(false);
  const [isDiagnosing, setIsDiagnosing] = useState(false);
  const [diagResults, setDiagResults] = useState<{
    tested: boolean;
    afiliadosWritable: boolean;
    beneficiosWritable: boolean;
    localidadesWritable: boolean;
    orgAfiliadosExists: boolean;
    orgBeneficiosExists: boolean;
    seccionBeneficiosExists: boolean;
    errors: string[];
  }>({
    tested: false,
    afiliadosWritable: false,
    beneficiosWritable: false,
    localidadesWritable: false,
    orgAfiliadosExists: false,
    orgBeneficiosExists: false,
    seccionBeneficiosExists: false,
    errors: []
  });

  const copyScript = () => {
    navigator.clipboard.writeText(SQL_SCRIPT);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
    showToast('success', 'Script SQL copiado al portapapeles');
  };

  const runDiagnostics = async () => {
    setIsDiagnosing(true);
    const errors: string[] = [];
    let afiliadosOk = false;
    let beneficiosOk = false;
    let localidadesOk = false;
    let orgAfilOk = false;
    let orgBenOk = false;
    let seccionBenOk = false;

    try {
      // 1. Check if organizacion column exists in afiliados
      const orgCheck = await supabase.from('afiliados').select('organizacion').limit(1);
      if (orgCheck.error) {
        errors.push(`Columna 'organizacion' en afiliados: No detectada (${orgCheck.error.message})`);
      } else {
        orgAfilOk = true;
      }

      // Check if organizacion column exists in beneficios
      const benOrgCheck = await supabase.from('beneficios').select('organizacion').limit(1);
      if (benOrgCheck.error) {
        errors.push(`Columna 'organizacion' en beneficios: No detectada (${benOrgCheck.error.message})`);
      } else {
        orgBenOk = true;
      }

      // Check if seccion column exists in beneficios
      const benSeccionCheck = await supabase.from('beneficios').select('seccion').limit(1);
      if (benSeccionCheck.error) {
        errors.push(`Columna 'seccion' en beneficios: No detectada (${benSeccionCheck.error.message})`);
      } else {
        seccionBenOk = true;
      }

      // 2. Test insert/rollback or check RLS on localidades
      const locTest = await supabase.from('localidades').insert([{
        localidad: '__test_probe__',
        provincia: '__test__'
      }]).select();

      if (locTest.error) {
        errors.push(`Localidades: ${locTest.error.message}`);
      } else {
        localidadesOk = true;
        // Clean up test probe
        if (locTest.data?.[0]?.id) {
          await supabase.from('localidades').delete().eq('id', locTest.data[0].id);
        }
      }

      // 3. Test insert/delete on beneficios
      const benTest = await supabase.from('beneficios').insert([{
        nombre_empresa: '__test_probe__',
        beneficio: '__test__',
        localidad: '__test__',
        direccion: '__test__',
        organizacion: 'AMBAS'
      }]).select();

      if (benTest.error) {
        errors.push(`Beneficios: ${benTest.error.message}`);
      } else {
        beneficiosOk = true;
        if (benTest.data?.[0]?.id) {
          await supabase.from('beneficios').delete().eq('id', benTest.data[0].id);
        }
      }

      // 4. Test insert/delete on afiliados
      const afilTest = await supabase.from('afiliados').insert([{
        dni: '00000000_PROBE',
        nombre_completo: 'Test Probe',
        correo: 'probe@test.com',
        contrasena: 'probe123',
        organizacion: 'SUTIAGA',
        familiares: []
      }]).select();

      if (afilTest.error) {
        errors.push(`Afiliados: ${afilTest.error.message}`);
      } else {
        afiliadosOk = true;
        await supabase.from('afiliados').delete().eq('dni', '00000000_PROBE');
      }

      setDiagResults({
        tested: true,
        afiliadosWritable: afiliadosOk,
        beneficiosWritable: beneficiosOk,
        localidadesWritable: localidadesOk,
        orgAfiliadosExists: orgAfilOk,
        orgBeneficiosExists: orgBenOk,
        seccionBeneficiosExists: seccionBenOk,
        errors
      });

      if (afiliadosOk && beneficiosOk && localidadesOk && orgAfilOk && orgBenOk && seccionBenOk) {
        showToast('success', '¡Conexión y permisos verificados con éxito!');
        await onRefreshData();
      } else {
        showToast('warning', 'Se detectaron permisos bloqueados (RLS) o columnas faltantes. Ejecuta el script SQL abajo.');
      }
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : 'Error en diagnóstico';
      errors.push(msg);
      setDiagResults(prev => ({ ...prev, tested: true, errors }));
    } finally {
      setIsDiagnosing(false);
    }
  };

  const allGreen = diagResults.tested && 
    diagResults.afiliadosWritable && 
    diagResults.beneficiosWritable && 
    diagResults.localidadesWritable && 
    diagResults.orgAfiliadosExists &&
    diagResults.orgBeneficiosExists &&
    diagResults.seccionBeneficiosExists;

  return (
    <div className="space-y-6 max-w-4xl mx-auto">
      {/* Intro Header */}
      <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-xs">
        <div className="flex items-center gap-3 mb-2">
          <div className="p-2.5 rounded-xl bg-indigo-50 text-indigo-700">
            <Database className="w-6 h-6" />
          </div>
          <div>
            <h2 className="text-xl font-bold text-slate-900">Configuración de Base de Datos Supabase</h2>
            <p className="text-sm text-slate-500">
              Asegura que tu base de datos cuente con las tablas, las columnas de Organización y Sección, y los permisos necesarios.
            </p>
          </div>
        </div>
      </div>

      {/* Diagnostics Card */}
      <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-xs space-y-4">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <h3 className="font-bold text-slate-900 text-base">Diagnóstico de Permisos y Esquema</h3>
            <p className="text-xs text-slate-500">
              Verifica si la aplicación puede leer y escribir (Altas, Bajas, Modificaciones) en Supabase.
            </p>
          </div>
          <button
            onClick={runDiagnostics}
            disabled={isDiagnosing}
            className="inline-flex items-center gap-2 px-4 py-2 text-sm font-semibold text-white bg-indigo-600 hover:bg-indigo-700 disabled:opacity-50 rounded-xl shadow-xs transition-all"
          >
            {isDiagnosing ? (
              <RefreshCw className="w-4 h-4 animate-spin" />
            ) : (
              <Play className="w-4 h-4" />
            )}
            <span>{isDiagnosing ? 'Comprobando...' : 'Comprobar Permisos Ahora'}</span>
          </button>
        </div>

        {diagResults.tested && (
          <div className={`p-4 rounded-xl border ${
            allGreen ? 'bg-emerald-50 border-emerald-200' : 'bg-amber-50 border-amber-200'
          }`}>
            <div className="flex items-start gap-3">
              {allGreen ? (
                <CheckCircle2 className="w-5 h-5 text-emerald-600 shrink-0 mt-0.5" />
              ) : (
                <ShieldAlert className="w-5 h-5 text-amber-600 shrink-0 mt-0.5" />
              )}
              <div className="flex-1 text-sm">
                <div className="font-bold text-slate-900">
                  {allGreen 
                    ? '¡Todo configurado correctamente!' 
                    : 'Atención: Se requiere ejecutar el script SQL en Supabase'}
                </div>
                <div className="text-xs text-slate-600 mt-1 space-y-1">
                  <div className="flex items-center gap-2">
                    <span>Tabla Afiliados (Escritura):</span>
                    <span className={`font-bold ${diagResults.afiliadosWritable ? 'text-emerald-700' : 'text-rose-600'}`}>
                      {diagResults.afiliadosWritable ? '✓ Habilitada' : '✗ Bloqueada por RLS'}
                    </span>
                  </div>
                  <div className="flex items-center gap-2">
                    <span>Columna Organización en Afiliados:</span>
                    <span className={`font-bold ${diagResults.orgAfiliadosExists ? 'text-emerald-700' : 'text-rose-600'}`}>
                      {diagResults.orgAfiliadosExists ? '✓ Presente' : '✗ Falta agregar'}
                    </span>
                  </div>
                  <div className="flex items-center gap-2">
                    <span>Tabla Beneficios (Escritura):</span>
                    <span className={`font-bold ${diagResults.beneficiosWritable ? 'text-emerald-700' : 'text-rose-600'}`}>
                      {diagResults.beneficiosWritable ? '✓ Habilitada' : '✗ Bloqueada por RLS'}
                    </span>
                  </div>
                  <div className="flex items-center gap-2">
                    <span>Columna Organización en Beneficios:</span>
                    <span className={`font-bold ${diagResults.orgBeneficiosExists ? 'text-emerald-700' : 'text-rose-600'}`}>
                      {diagResults.orgBeneficiosExists ? '✓ Presente' : '✗ Falta agregar'}
                    </span>
                  </div>
                  <div className="flex items-center gap-2">
                    <span>Columna Sección en Beneficios:</span>
                    <span className={`font-bold ${diagResults.seccionBeneficiosExists ? 'text-emerald-700' : 'text-rose-600'}`}>
                      {diagResults.seccionBeneficiosExists ? '✓ Presente' : '✗ Falta agregar'}
                    </span>
                  </div>
                  <div className="flex items-center gap-2">
                    <span>Tabla Localidades (Escritura):</span>
                    <span className={`font-bold ${diagResults.localidadesWritable ? 'text-emerald-700' : 'text-rose-600'}`}>
                      {diagResults.localidadesWritable ? '✓ Habilitada' : '✗ Bloqueada por RLS'}
                    </span>
                  </div>
                </div>
              </div>
            </div>
          </div>
        )}
      </div>

      {/* Steps Guide */}
      <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-xs space-y-4">
        <h3 className="font-bold text-slate-900 text-base">Instrucciones Rápidas (1 Minuto)</h3>
        
        <div className="grid grid-cols-1 md:grid-cols-3 gap-4 text-sm">
          <div className="p-4 rounded-xl bg-slate-50 border border-slate-200">
            <span className="w-6 h-6 rounded-full bg-blue-600 text-white font-bold text-xs flex items-center justify-center mb-2">1</span>
            <h4 className="font-bold text-slate-800 mb-1">Copia el Script</h4>
            <p className="text-xs text-slate-500">
              Haz clic en el botón <strong>&ldquo;Copiar Script SQL&rdquo;</strong> que aparece abajo en el recuadro de código.
            </p>
          </div>

          <div className="p-4 rounded-xl bg-slate-50 border border-slate-200">
            <span className="w-6 h-6 rounded-full bg-blue-600 text-white font-bold text-xs flex items-center justify-center mb-2">2</span>
            <h4 className="font-bold text-slate-800 mb-1">Abre el SQL Editor</h4>
            <p className="text-xs text-slate-500">
              Ingresa al panel de Supabase y ve a la sección <strong>SQL Editor</strong> en la barra lateral.
            </p>
            <a
              href="https://supabase.com/dashboard/project/yufhvklzfrbvxmmuejxh/sql"
              target="_blank"
              rel="noreferrer"
              className="inline-flex items-center gap-1 text-xs font-semibold text-blue-600 hover:text-blue-800 mt-2"
            >
              <span>Abrir SQL Editor</span>
              <ExternalLink className="w-3 h-3" />
            </a>
          </div>

          <div className="p-4 rounded-xl bg-slate-50 border border-slate-200">
            <span className="w-6 h-6 rounded-full bg-blue-600 text-white font-bold text-xs flex items-center justify-center mb-2">3</span>
            <h4 className="font-bold text-slate-800 mb-1">Pega y Presiona Run</h4>
            <p className="text-xs text-slate-500">
              Pega el script y presiona el botón verde <strong>Run</strong>. Luego vuelve aquí y haz clic en &ldquo;Comprobar Permisos Ahora&rdquo;.
            </p>
          </div>
        </div>
      </div>

      {/* SQL Script Viewer */}
      <div className="bg-slate-900 rounded-2xl border border-slate-800 overflow-hidden shadow-xl text-slate-200">
        <div className="px-5 py-3.5 bg-slate-950/80 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <div className="w-3 h-3 rounded-full bg-rose-500/80"></div>
            <div className="w-3 h-3 rounded-full bg-amber-500/80"></div>
            <div className="w-3 h-3 rounded-full bg-emerald-500/80"></div>
            <span className="text-xs font-mono text-slate-400 ml-2">supabase_setup.sql</span>
          </div>

          <button
            onClick={copyScript}
            className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold text-slate-200 bg-slate-800 hover:bg-slate-700 active:scale-95 rounded-lg transition-all"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-400" />
                <span className="text-emerald-400">¡Copiado!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copiar Script SQL</span>
              </>
            )}
          </button>
        </div>

        <div className="p-5 max-h-96 overflow-y-auto font-mono text-xs text-slate-300 leading-relaxed">
          <pre>{SQL_SCRIPT}</pre>
        </div>
      </div>
    </div>
  );
};
