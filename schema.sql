-- 5. PERMISOS Y SEGURIDAD A NIVEL DE FILAS (RLS)
-- Para que el sistema de gestión pueda crear, editar y eliminar con la clave pública (anon),
-- deshabilitamos RLS o agregamos políticas permisivas:

ALTER TABLE afiliados DISABLE ROW LEVEL SECURITY;
ALTER TABLE beneficios DISABLE ROW LEVEL SECURITY;
ALTER TABLE localidades DISABLE ROW LEVEL SECURITY;

-- O si prefieres mantener RLS activo con políticas públicas:
DROP POLICY IF EXISTS "Permitir acceso publico afiliados" ON afiliados;
CREATE POLICY "Permitir acceso publico afiliados" ON afiliados FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir acceso publico beneficios" ON beneficios;
CREATE POLICY "Permitir acceso publico beneficios" ON beneficios FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir acceso publico localidades" ON localidades;
CREATE POLICY "Permitir acceso publico localidades" ON localidades FOR ALL USING (true) WITH CHECK (true);

